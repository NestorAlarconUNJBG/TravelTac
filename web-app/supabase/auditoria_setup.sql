-- Run in the Supabase SQL Editor after creating the TravelTac tables.
-- Records content changes made through the database, regardless of client.

create table if not exists public.bitacora_auditoria (
  id bigint generated by default as identity primary key,
  usuario_id bigint references public.usuarios_admin(id) on delete set null,
  accion varchar(100) not null,
  tabla_afectada varchar(100) not null,
  registro_id bigint,
  detalles_cambio jsonb,
  fecha_hora timestamptz default now()
);

create or replace function public.traveltac_is_active_admin()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1
    from public.usuarios_admin as admin
    where lower(admin.correo) = lower((select auth.jwt() ->> 'email'))
      and admin.estado = 'activo'
  );
$$;

revoke all on function public.traveltac_is_active_admin() from public;
grant execute on function public.traveltac_is_active_admin() to authenticated;

-- The browser only needs these non-sensitive profile fields.
revoke select on table public.usuarios_admin from public, anon, authenticated;
grant select (id, nombre_completo, correo, rol, institucion, estado)
on table public.usuarios_admin to authenticated;

create or replace function public.traveltac_audit_content_change()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  old_record jsonb;
  new_record jsonb;
  changed_record jsonb;
  actor_id bigint;
  affected_record_id bigint;
  actor_email text;
begin
  if tg_op = 'INSERT' then
    new_record := to_jsonb(new) - 'contrasena_hash' - 'password' - 'token';
    changed_record := jsonb_build_object('despues', new_record);
  elsif tg_op = 'UPDATE' then
    old_record := to_jsonb(old) - 'contrasena_hash' - 'password' - 'token';
    new_record := to_jsonb(new) - 'contrasena_hash' - 'password' - 'token';
    if old_record is not distinct from new_record then
      return new;
    end if;
    changed_record := jsonb_build_object(
      'antes', old_record,
      'despues', new_record
    );
  else
    old_record := to_jsonb(old) - 'contrasena_hash' - 'password' - 'token';
    changed_record := jsonb_build_object('antes', old_record);
  end if;

  actor_email := lower((select auth.jwt() ->> 'email'));
  if actor_email is not null then
    select admin.id
    into actor_id
    from public.usuarios_admin as admin
    where lower(admin.correo) = actor_email
      and admin.estado = 'activo'
    order by admin.id
    limit 1;
  end if;

  if tg_op = 'DELETE' then
    if old_record ? 'id' then
      affected_record_id := (old_record ->> 'id')::bigint;
    elsif old_record ? 'poi_id' then
      affected_record_id := (old_record ->> 'poi_id')::bigint;
    elsif old_record ? 'ruta_id' then
      affected_record_id := (old_record ->> 'ruta_id')::bigint;
    end if;
  else
    if new_record ? 'id' then
      affected_record_id := (new_record ->> 'id')::bigint;
    elsif new_record ? 'poi_id' then
      affected_record_id := (new_record ->> 'poi_id')::bigint;
    elsif new_record ? 'ruta_id' then
      affected_record_id := (new_record ->> 'ruta_id')::bigint;
    end if;
  end if;

  insert into public.bitacora_auditoria (
    usuario_id,
    accion,
    tabla_afectada,
    registro_id,
    detalles_cambio
  )
  values (
    actor_id,
    tg_op,
    tg_table_name,
    affected_record_id,
    changed_record
  );

  if tg_op = 'DELETE' then
    return old;
  end if;
  return new;
end;
$$;

revoke all on function public.traveltac_audit_content_change() from public;

alter table public.bitacora_auditoria enable row level security;
grant select on table public.bitacora_auditoria to authenticated;
revoke insert, update, delete, truncate
on table public.bitacora_auditoria from public, anon, authenticated;
grant usage, select on sequence public.bitacora_auditoria_id_seq to authenticated;

drop policy if exists "traveltac_active_admin_read_audit" on public.bitacora_auditoria;
create policy "traveltac_active_admin_read_audit"
on public.bitacora_auditoria
for select
to authenticated
using (public.traveltac_is_active_admin());

